# 位置対応の整合性チェック（起動時に一度だけ）。
if len(_KYUJITAI) != len(_SHINJITAI):
    raise RuntimeError(
        f"kreplace 変換表の長さが不一致: 旧字={len(_KYUJITAI)} 新字={len(_SHINJITAI)}"
    )

# 旧字→新字の変換マップ。旧字側に重複があれば後勝ちになるため検出して弾く。
_TABLE: dict[int, str] = {}
_dupes = []
for _k, _s in zip(_KYUJITAI, _SHINJITAI):
    cp = ord(_k)
    if cp in _TABLE and _TABLE[cp] != _s:
        _dupes.append(_k)
    _TABLE[cp] = _s
if _dupes:
    raise RuntimeError(f"kreplace 変換表に旧字側の重複があります: {''.join(_dupes)}")


def to_shinjitai(text: str) -> str:
    """旧字体・異体字を新字体へ変換する。

    1. NFC正規化で CJK互換漢字（正準分解を持つ U+FAxx など）を標準字体へ畳む
    2. kreplace 変換表で旧字→新字を置換する
    """
    if not text:
        return text
    normalized = unicodedata.normalize("NFC", text)
    return normalized.translate(_TABLE)


